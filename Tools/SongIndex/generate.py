#!/usr/bin/env python3
"""Regenerates Core/SongIndexData.swift from a saved song-index web page.

    python3 -I Tools/SongIndex/generate.py page.html Core/SongIndexData.swift

The page embeds every song as `const song_collection = [...]`. Each entry gives a
title, artist, tempo, genre and the name of a default-library beat. Only
those facts are kept; `SongIndex.swift` maps each beat name to a PedalBeat groove.
"""
import json
import re
import sys


def clean(s):
    s = (s or "").strip()
    if "Ã" in s or "â€" in s:  # UTF-8 read as Latin-1 on the source site
        try:
            s = s.encode("latin-1").decode("utf-8")
        except UnicodeError:
            pass
    s = s.replace("’", "'").replace("‘", "'")
    return re.sub(r"\s+", " ", s).strip()


def main(src, dst):
    html = open(src, encoding="utf-8").read()
    marker = "const song_collection = "
    start = html.index(marker) + len(marker)
    data, _ = json.JSONDecoder().raw_decode(html[start:])

    rows, seen = [], set()
    for d in data:
        title, artist = clean(d.get("title")), clean(d.get("artist"))
        style = clean((d.get("beat") or {}).get("bbName"))
        genre = clean((d.get("genre") or {}).get("name"))
        bpm = d.get("bpm") or 0
        if not title or not style or not (30 <= bpm <= 300):
            continue
        key = (title.lower(), artist.lower(), bpm, style)
        if key in seen:
            continue
        seen.add(key)
        rows.append((title, artist, str(bpm), genre, style))
    rows.sort(key=lambda r: (r[0].lower(), r[1].lower()))

    body = "\n".join("\t".join(r) for r in rows)
    assert '"""#' not in body
    with open(dst, "w", encoding="utf-8") as f:
        f.write("// Generated by Tools/SongIndex/generate.py. Do not edit by hand.\n")
        f.write("// Columns: title, artist, bpm, genre, beat style (tab separated).\n\n")
        f.write("extension SongIndex {\n")
        f.write(f"    static let entryCount = {len(rows)}\n")
        f.write('    static let rawData = #"""\n')
        f.write(body)
        f.write('\n"""#\n}\n')
    print(f"{len(rows)} songs -> {dst}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
